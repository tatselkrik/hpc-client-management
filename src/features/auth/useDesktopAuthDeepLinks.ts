import { isTauri } from "@tauri-apps/api/core";
import { getCurrent, onOpenUrl } from "@tauri-apps/plugin-deep-link";
import { useEffect } from "react";
import { confirm } from "@tauri-apps/plugin-dialog";

import { supabase } from "../../lib/supabase";
import { allowInteractiveSession, acceptConfirmedInvitation, lockClinicalSession } from "../../lib/clinicalSession";

const AUTH_DEEP_LINK_SCHEME =
  (import.meta.env.VITE_AUTH_DEEP_LINK_SCHEME || "hpc-client-management")
    .trim()
    .replace(/:$/, "");
const AUTH_DEEP_LINK_PROTOCOL = `${AUTH_DEEP_LINK_SCHEME}:`;
const AUTH_DEEP_LINK_HOST = "auth";
const INVITATION_PATH = "/invite";

export function isApprovedInvitationDeepLink(rawUrl: string) {
  try {
    const url = new URL(rawUrl);
    return (
      url.protocol === AUTH_DEEP_LINK_PROTOCOL &&
      !url.username && !url.password && !url.port &&
      url.hostname === AUTH_DEEP_LINK_HOST &&
      url.pathname === INVITATION_PATH
    );
  } catch {
    return false;
  }
}

export async function acceptDesktopInvitationDeepLink(rawUrl: string) {
  if (!isApprovedInvitationDeepLink(rawUrl)) return false;

  const url = new URL(rawUrl);
  const fragment = new URLSearchParams(url.hash.replace(/^#/, ""));
  const accessToken = fragment.get("access_token");
  const refreshToken = fragment.get("refresh_token");
  const authorizationCode = url.searchParams.get("code");

  // An invitation must be explicit, cannot silently replace a signed-in
  // account, and must be confirmed for the server-verified recipient.
  const type = fragment.get("type") ?? url.searchParams.get("type");
  if (type !== "invite") return false;
  const current = await supabase.auth.getSession();
  if (current.error || current.data.session) return false;
  if (accessToken && refreshToken) {
    const recipient = await supabase.auth.getUser(accessToken);
    if (recipient.error || !recipient.data.user?.email) return false;
    const message = `Accept the account invitation for ${recipient.data.user.email}?`;
    const accepted = isTauri() ? await confirm(message, { title: "Accept invitation", kind: "info" }) : window.confirm(message);
    if (!accepted) return false;
    const beforeAccept = await supabase.auth.getSession();
    if (beforeAccept.error || beforeAccept.data.session) return false;
    allowInteractiveSession(recipient.data.user.id);
  } else if (!authorizationCode) return false;
  // PKCE exchanges still require the verifier generated by this client.

  window.history.replaceState(
    null,
    document.title,
    `${window.location.pathname}${window.location.search}#account-invitation`
  );

  if (accessToken && refreshToken) {
    const { data, error } = await supabase.auth.setSession({
      access_token: accessToken,
      refresh_token: refreshToken,
    });
    if (!error && data.user) acceptConfirmedInvitation(data.user.id);
    return !error;
  }

  if (authorizationCode) {
    const { data, error } = await supabase.auth.exchangeCodeForSession(authorizationCode);
    if (error || !data.user?.email) {
      lockClinicalSession();
      void supabase.auth.signOut().catch(() => undefined);
      return false;
    }
    if (!error && data.user?.email) {
      const message = `Accept the account invitation for ${data.user.email}?`;
      const accepted = isTauri() ? await confirm(message, { title: "Accept invitation", kind: "info" }) : window.confirm(message);
      if (!accepted) { lockClinicalSession(); void supabase.auth.signOut().catch(() => undefined); return false; }
      acceptConfirmedInvitation(data.user.id);
    }
    return !error;
  }

  return false;
}

export function useDesktopAuthDeepLinks() {
  useEffect(() => {
    if (!isTauri()) return;

    let disposed = false;
    let stopListening: (() => void) | undefined;

    const processUrls = async (urls: string[] | null) => {
      if (!urls || disposed) return;

      for (const url of urls) {
        if (await acceptDesktopInvitationDeepLink(url)) break;
      }
    };

    void getCurrent().then(processUrls).catch(() => undefined);
    void onOpenUrl((urls) => {
      void processUrls(urls).catch(() => undefined);
    }).then((unlisten) => {
      if (disposed) {
        unlisten();
      } else {
        stopListening = unlisten;
      }
    }).catch(() => undefined);

    return () => {
      disposed = true;
      stopListening?.();
    };
  }, []);
}
